#!/usr/bin/env python3
"""Rebuild vault/index.md from the pages themselves, and audit the graph.

    bin/vault-index.py            rebuild index.md, print warnings
    bin/vault-index.py --check    audit only, write nothing (exit 1 on problems)

The index is generated, never hand-edited: a hand-maintained index goes stale
and a stale index is worse than none, because it still gets trusted.
"""

from __future__ import annotations

import datetime as dt
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from friday_md import Page, load_vault, vault_root  # noqa: E402

FOLDERS = [
    ("raw", "Captured, unedited. Append-only."),
    ("wiki", "Distilled knowledge. One page per topic, rewritten as it is learned."),
    ("outputs", "Everything the system shipped, dated."),
]


def audit(pages: list[Page]) -> list[str]:
    """Schema violations, in the order they matter."""
    titles = {p.title for p in pages}
    problems = []
    for p in pages:
        for f in p.missing_fields():
            problems.append(f"{p.path}: missing frontmatter field '{f}'")
        if not p.summary:
            continue
        if len(p.summary) > 200:
            problems.append(f"{p.path}: summary is {len(p.summary)} chars (max 200)")
        for link in p.links:
            if link not in titles:
                problems.append(f"{p.path}: dead wikilink [[{link}]]")
        folder, kind = p.folder, p.meta.get("type")
        if folder in ("raw", "wiki", "outputs"):
            expected = {"raw": "raw", "wiki": "wiki", "outputs": "output"}[folder]
            if kind != expected:
                problems.append(f"{p.path}: type '{kind}' but sits in {folder}/ (expected '{expected}')")
        if folder == "outputs" and not os.path.basename(p.path)[:10].count("-") == 2:
            problems.append(f"{p.path}: outputs/ filenames must start with YYYY-MM-DD")
    orphans = [p for p in pages
               if not p.links and not any(p.title in q.links for q in pages)
               and p.meta.get("type") not in ("log", "index")]
    problems += [f"{p.path}: orphan — links to nothing and nothing links to it" for p in orphans]
    return problems


def render(pages: list[Page], root: str) -> str:
    today = dt.date.today().isoformat()
    counts = {f: sum(1 for p in pages if p.folder == f) for f, _ in FOLDERS}
    out = [
        "---",
        "title: Index",
        "type: index",
        "tags: [meta, index]",
        "created: 2026-08-13",
        f"updated: {today}",
        "summary: Every page in the vault with a one-line hook. Generated by "
        "bin/vault-index.py — do not edit by hand.",
        "---",
        "",
        "# Index",
        "",
        f"Generated {today} from {len(pages)} pages. Rebuild with `bin/vault-index.py`.",
        f"Never edit this file by hand — the next rebuild discards it.",
        "",
        "| | pages |",
        "|---|---|",
    ]
    out += [f"| `{f}/` | {counts[f]} |" for f, _ in FOLDERS]
    out.append("")

    for folder, blurb in FOLDERS:
        group = [p for p in pages if p.folder == folder]
        out += [f"## `{folder}/`", "", f"*{blurb}*", ""]
        if not group:
            out += ["Empty.", ""]
            continue
        if folder == "outputs":
            group = sorted(group, key=lambda p: p.path, reverse=True)
        for p in group:
            hook = p.summary or "*no summary — add one*"
            out.append(f"- [[{p.title}]] — {hook}")
        out.append("")

    loose = [p for p in pages if p.folder not in dict(FOLDERS)]
    if loose:
        out += ["## Vault root", ""]
        out += [f"- [[{p.title}]] — {p.summary}" for p in loose]
        out.append("")

    tags: dict[str, int] = {}
    for p in pages:
        for t in p.meta.get("tags") or []:
            tags[str(t)] = tags.get(str(t), 0) + 1
    if tags:
        out += ["## Tags in use", "",
                "Reuse one of these before coining a new tag.", "",
                " ".join(f"`{t}`({n})" for t, n in sorted(tags.items())), ""]
    return "\n".join(out)


def main() -> int:
    check_only = "--check" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = vault_root(args[0] if args else None)
    if not os.path.isdir(root):
        print(f"no vault at {root}", file=sys.stderr)
        return 2

    pages = load_vault(root)
    problems = audit(pages)

    if not check_only:
        path = os.path.join(root, "index.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render(pages, root) + "\n")
        print(f"index.md rebuilt — {len(pages)} pages")

    if problems:
        print(f"\n{len(problems)} schema problem(s):", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    print("schema clean — frontmatter complete, no dead links, no orphans")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
